-- PostgreSQL side of the migration.
--
--   app     the 3 tables already strangled out of the monolith (30%). No
--           foreign keys to books/customers/orders: those still live in
--           MySQL, so integrity across the two servers is the application's
--           job until they move too.
--   native  all 10 tables as plain PostgreSQL tables: what the schema looks
--           like once the migration is done. Baseline only.
--
-- The 7 legacy tables reach PostgreSQL as foreign tables, see fdw.sql.
-- Primary keys only here; secondary indexes come after the bulk load
-- (indexes.sql). timestamp(0) mirrors MySQL's DATETIME.

CREATE SCHEMA app;
CREATE SCHEMA native;

CREATE TABLE app.reviews (
  id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id       integer      NOT NULL, -- legacy books.id
  customer_id   integer      NOT NULL, -- legacy customers.id
  rating        smallint     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  title         varchar(200) NOT NULL,
  body          text         NOT NULL,
  helpful_votes integer      NOT NULL DEFAULT 0,
  created_at    timestamp(0) NOT NULL
);

CREATE TABLE app.inventory (
  book_id        integer      NOT NULL, -- legacy books.id
  warehouse_code varchar(10)  NOT NULL,
  quantity       integer      NOT NULL,
  reorder_level  integer      NOT NULL,
  updated_at     timestamp(0) NOT NULL,
  PRIMARY KEY (book_id, warehouse_code)
);

CREATE TABLE app.shipments (
  id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        integer      NOT NULL, -- legacy orders.id
  carrier         varchar(20)  NOT NULL,
  tracking_number varchar(40)  NOT NULL,
  status          varchar(20)  NOT NULL,
  shipped_at      timestamp(0) NOT NULL,
  delivered_at    timestamp(0)
);

-- Straight ports of sql/mysql/legacy_tables.sql
CREATE TABLE native.publishers (
  id           integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         varchar(200) NOT NULL,
  country      char(2)      NOT NULL,
  founded_year smallint,
  created_at   timestamp(0) NOT NULL
);

CREATE TABLE native.authors (
  id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name varchar(100) NOT NULL,
  last_name  varchar(100) NOT NULL,
  birth_year smallint,
  country    char(2)      NOT NULL,
  created_at timestamp(0) NOT NULL
);

CREATE TABLE native.books (
  id           integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isbn         char(13)      NOT NULL,
  title        varchar(255)  NOT NULL,
  publisher_id integer       NOT NULL,
  genre        varchar(40)   NOT NULL,
  language     char(2)       NOT NULL,
  published_on date          NOT NULL,
  pages        smallint      NOT NULL,
  price        numeric(10,2) NOT NULL,
  created_at   timestamp(0)  NOT NULL
);

CREATE TABLE native.book_authors (
  book_id      integer  NOT NULL,
  author_id    integer  NOT NULL,
  author_order smallint NOT NULL,
  PRIMARY KEY (book_id, author_id)
);

CREATE TABLE native.customers (
  id           integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email        varchar(255) NOT NULL,
  full_name    varchar(200) NOT NULL,
  country      char(2)      NOT NULL,
  loyalty_tier varchar(10)  NOT NULL,
  created_at   timestamp(0) NOT NULL
);

CREATE TABLE native.orders (
  id               integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id      integer       NOT NULL,
  status           varchar(20)   NOT NULL,
  ordered_at       timestamp(0)  NOT NULL,
  total_amount     numeric(12,2) NOT NULL,
  shipping_country char(2)       NOT NULL
);

CREATE TABLE native.order_items (
  id         integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   integer       NOT NULL,
  line_no    smallint      NOT NULL,
  book_id    integer       NOT NULL,
  quantity   smallint      NOT NULL,
  unit_price numeric(10,2) NOT NULL
);

-- The migrated tables, identical to app.*
CREATE TABLE native.reviews (LIKE app.reviews INCLUDING ALL);
CREATE TABLE native.inventory (LIKE app.inventory INCLUDING ALL);
CREATE TABLE native.shipments (LIKE app.shipments INCLUDING ALL);
